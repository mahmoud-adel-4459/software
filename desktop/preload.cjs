'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld(
  'desktop',
  Object.freeze({
    info: () => ipcRenderer.invoke('app:info'),
    copyText: (text) => ipcRenderer.invoke('app:copy-text', text),
    configure: (serverUrl) => ipcRenderer.invoke('app:configure', serverUrl),
    importCA: () => ipcRenderer.invoke('app:import-ca'),
    importBundledCA: () => ipcRenderer.invoke('app:import-bundled-ca'),
    exportDevice: () => ipcRenderer.invoke('app:export-device'),
    network: () => ipcRenderer.invoke('app:network'),
    setNetworkRole: (role) => ipcRenderer.invoke('app:set-network-role', role),
    pair: (arg) => ipcRenderer.invoke('app:pair', arg),
    login: (credentials) => ipcRenderer.invoke('app:login', credentials),
    logout: () => ipcRenderer.invoke('app:logout'),
    request: (method, path, data, requestId) => ipcRenderer.invoke('app:request', { method, path, data, requestId }),
    qr: (militaryNo) => ipcRenderer.invoke('app:qr', militaryNo),
    qrVisitor: (visitorId) => ipcRenderer.invoke('app:qrVisitor', visitorId),
    printers: () => ipcRenderer.invoke('app:printers'),
    testPrint: (arg) => ipcRenderer.invoke('app:test-print', arg),
    document: (arg) => ipcRenderer.invoke('app:document', arg),
    exportReport: (filter) => ipcRenderer.invoke('app:export-report', filter),
    pickAttachment: () => ipcRenderer.invoke('app:pick-attachment'),
    saveAttachment: (id) => ipcRenderer.invoke('app:save-attachment', id),
    saveBackup: (id) => ipcRenderer.invoke('app:backup-save', id),
    importBackup: () => ipcRenderer.invoke('app:backup-import'),
    previewLegacy: () => ipcRenderer.invoke('app:legacy-preview'),
    excelExport: (arg) => ipcRenderer.invoke('app:excel-export', arg),
    excelTemplate: (arg) => ipcRenderer.invoke('app:excel-template', arg),
    excelImport: () => ipcRenderer.invoke('app:excel-import'),
    applyLegacy: (confirmation) => ipcRenderer.invoke('app:legacy-apply', confirmation),
  }),
);
